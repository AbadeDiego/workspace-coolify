import test from 'node:test';
import vm from 'node:vm';
import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {workspaceDomain} from '../src/domain.mjs';

test('Marketing exibe valor, aprovação e agenda no detalhe, calendário e atividades',async()=>{
  const db=JSON.parse(await readFile(new URL('../src/seed.json',import.meta.url),'utf8'));
  db['material-experiments']=[];db['material-worklogs']=[];
  for(const user of db.users)user.active=true;
  const model={db,sequence:1000};
  const startup=db.memberships.find(m=>m.user_id==='3').startup_id;
  const day=new Intl.DateTimeFormat('en-CA',{timeZone:'America/Sao_Paulo'}).format(new Date());
  const call=async(user,path,body)=>{const r=await workspaceDomain(model,user)('/api/'+path,'POST',body);assert(r.ok,await r.clone().text());return r.json();};
  const piece=await call('1','marketing',{startup_id:startup,creator_id:'3',title:'Agenda visual',format:'reel',paid_production:'yes',planned_date:day});
  await call('3','marketing/'+piece.id+'/workflow',{action:'submit',url:'https://example.test/versao'});
  await call('1','marketing/'+piece.id+'/workflow',{action:'approve'});
  await call('3','marketing/'+piece.id+'/workflow',{action:'publish',network:'Instagram',account:'@conta',caption:'Legenda',published_at:day+'T12:00:00Z',post_url:'https://example.test/reel'});
  const published=db.marketing.find(p=>p.id===piece.id),nodes=new Map();
  const el=()=>({innerHTML:'',value:'',open:false,showModal(){this.open=true},close(){},focus(){},setAttribute(){},classList:{add(){},remove(){},toggle(){},contains(){return false}},querySelector:()=>el(),querySelectorAll:()=>[]});
  const document={addEventListener(){},querySelector(s){if(!nodes.has(s))nodes.set(s,el());return nodes.get(s)},querySelectorAll:()=>[]};
  const ctx=vm.createContext({document,window:{matchMedia:()=>({matches:false,addEventListener(){}})},URL,console,setTimeout,fetch:async(path,opts={})=>workspaceDomain(model,'3')(path,opts.method||'GET',JSON.parse(opts.body||'{}'))});
  const js=await readFile(new URL('../public/app.js',import.meta.url),'utf8');
  vm.runInContext('const MATERIAL_SPACE="materials-palma";const taskPayRoles=["comercial","marketing","marketing_externo"];'+js.slice(js.indexOf('const $ ='),js.lastIndexOf('(async () => {')),ctx);
  const run=s=>vm.runInContext(s,ctx);
  ctx.me=db.users.find(u=>u.id==='3');ctx.startups=db.startups.filter(s=>s.id===startup);ctx.piece=published;
  run('Object.assign(state,{me,startups,users:[me],section:"marketing",startup:"",period:"all",calendar:0})');
  await run('contentDetail(piece)');
  assert.match(nodes.get('#modal-body').innerHTML,/Produção do Reel · R\$ 100,00/);
  assert.match(nodes.get('#modal-body').innerHTML,/Qualidade aprovada/);
  assert.match(nodes.get('#modal-body').innerHTML,/Agenda de Stories/);
  assert.equal((nodes.get('#modal-body').innerHTML.match(/data-action="task-detail"/g)||[]).length,6);
  const board=await run('marketingPage()');assert.match(board,/Stories programados/);
  run('state.view.marketing="calendar"');
  const calendar=await run('marketingPage()');assert.match(calendar,/Publicações e repostagens/);assert.match(calendar,/data-action="task-detail"/);
  ctx.taskId=piece.production_task_id;
  await run('taskDetail(taskId)');assert.match(nodes.get('#modal-body').innerHTML,/Produção do Reel/);
  await run('contentAction(piece,"publish")');assert.match(nodes.get('#modal-body').innerHTML,/1, 3, 7, 14, 21 e 28/);
});
